def get_admin_text(text_key: str, language: str = 'ru', **kwargs) -> str:
    try:
        from admin.methods import TextEditorMethodsDB
        text_editor_db = TextEditorMethodsDB()
        custom_text = text_editor_db.get_text('admin', text_key, language)
        if custom_text:
            if kwargs:
                return custom_text.format(**kwargs)
            return custom_text
    except:
        pass
    
    if language in TEXTS and text_key in TEXTS[language]:
        text = TEXTS[language][text_key]
        if kwargs:
            return text.format(**kwargs)
        return text
    
    if text_key in TEXTS['ru']:
        text = TEXTS['ru'][text_key]
        if kwargs:
            return text.format(**kwargs)
        return text
    
    return f"[{text_key}]"

